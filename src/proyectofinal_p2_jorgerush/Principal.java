    public void fechaHora() {

        Timer timer = new Timer(1000, e -> {
            String fecha = LocalDate.now().toString();
            String hora = String.format("%tr", LocalTime.now());
            FechaHora.setText(fecha + "   " + hora);
        });

        timer.start();

    }

